// Поиск по части названия или аббревиатуры, без учёта регистра
export const filterFaculties = (query: string): Faculty[] => {
  const needle = query.trim().toLowerCase();
  return FACULTIES.filter((item) => !needle || item.name.toLowerCase().includes(needle) || (item.short ?? '').toLowerCase().includes(needle));
};

// Для карточки профиля: аббревиатура, если есть; иначе то, что записано (полное название или старое значение)
export const shortFaculty = (name: string): string => FACULTIES.find((item) => item.name === name)?.short ?? name;
